"""Generate build/assets.h from assets/*.png and layout.json (run by make).

Images become const ARGB8888 arrays (0xAARRGGBB, straight alpha); layout values become #defines.
usage: gen_assets.py <assets dir> <layout.json> <out header>
"""
import glob
from collections import Counter
import json
import os
import sys
from PIL import Image, ImageDraw, ImageFont


def c_name(s):
    return ''.join(ch if ch.isalnum() else '_' for ch in s).upper()


# extra characters for fonts that show text from a phone (song titles): Latin-1, the Romanian letters and
# the other common Latin Extended-A ones, typographic quotes / dashes and the ellipsis used to cut long titles
EXTRA_CHARS = ''.join(chr(c) for c in range(0xc0, 0x100) if c not in (0xd7, 0xf7)) + '¡¿«»°·' + \
    'ăĂșȘțȚşŞţŢąĄćĆčČęĘěĚğĞıİłŁńŃőŐřŘśŚšŠűŰźŹżŻžŽ' + '‘’“”–—…'


def font_atlas(prefix, path, px, extra=''):
    """printable ASCII (+ extra characters) as alpha-only glyphs, all font_t.h rows tall, 4 bits per pixel
    (two pixels per byte, low nibble first); off[] counts pixels"""
    font = ImageFont.truetype(path, px)
    asc, desc = font.getmetrics()
    gh = asc + desc
    chars = [chr(c) for c in range(32, 127)] + list(extra)
    offs, pix, widths = [], [], []
    for ch in chars:
        gw = max(1, round(font.getlength(ch)))
        im = Image.new('L', (gw, gh), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
        offs.append(len(pix)); widths.append(gw); pix += [(v * 15 + 127) // 255 for v in im.tobytes()]
    pix += [0] * (len(pix) & 1)
    data = bytes(pix[i] | pix[i + 1] << 4 for i in range(0, len(pix), 2))
    n = len(chars)
    body = ',\n'.join(', '.join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
    out = [f'static const uint16_t {prefix}_W[{n}] = {{ ' + ', '.join(map(str, widths)) + ' };',
           f'static const uint32_t {prefix}_OFF[{n}] = {{ ' + ', '.join(map(str, offs)) + ' };',
           f'static const uint8_t {prefix}_A[] = {{\n{body}\n}};']
    if extra:
        out.append(f'static const uint16_t {prefix}_CP[{len(extra)}] = {{ ' + ', '.join(str(ord(c)) for c in extra) + ' };')
    cp = f'{prefix}_CP' if extra else '0'
    out.append(f'static const font_t {prefix} = {{ {gh}, {len(extra)}, {prefix}_W, {prefix}_OFF, {prefix}_A, {cp} }};')
    return out


def main(assets, layout_path, out):
    lay = json.load(open(layout_path))
    lines = ['/* generated by tools/gen_assets.py from assets/ and layout.json - do not edit */',
             '#pragma once', '#include <stdint.h>',
             '/* an image: px (ARGB, straight alpha), or for a single-colour image a (alpha, 1 byte / pixel) + rgb */',
             'typedef struct { uint16_t w, h; const uint32_t *px; const uint8_t *a; uint32_t rgb; } img_t;', '']

    for path in sorted(glob.glob(os.path.join(assets, '*.png'))):
        name = os.path.splitext(os.path.basename(path))[0]
        im = Image.open(path).convert('RGBA')
        raw = im.tobytes()
        # one colour: the pixels that show (alpha >= 96) all of it; fainter edge pixels, whose colour a resize on a
        # transparent background darkened, take it too
        colours = Counter(raw[i:i + 3] for i in range(0, len(raw), 4) if raw[i + 3] >= 96)
        main = colours.most_common(1)[0][0] if colours else b'\0\0\0'
        if all(max(abs(a - b) for a, b in zip(c, main)) <= 6 for c in colours):
            a = raw[3::4]
            body = ',\n'.join(', '.join(str(v) for v in a[i:i + 32]) for i in range(0, len(a), 32))
            rgb = main[0] << 16 | main[1] << 8 | main[2]
            lines += [f'static const uint8_t a_{name}[] = {{\n{body}\n}};',
                      f'static const img_t IMG_{c_name(name)} = {{ {im.width}, {im.height}, 0, a_{name}, 0x{rgb:06x} }};', '']
            continue
        px = [(raw[i + 3] << 24) | (raw[i] << 16) | (raw[i + 1] << 8) | raw[i + 2] for i in range(0, len(raw), 4)]
        body = ',\n'.join(', '.join(f'0x{v:08x}' for v in px[i:i + 12]) for i in range(0, len(px), 12))
        lines += [f'static const uint32_t px_{name}[] = {{\n{body}\n}};',
                  f'static const img_t IMG_{c_name(name)} = {{ {im.width}, {im.height}, px_{name}, 0, 0 }};', '']

    s = lay['strip']
    bg = int(s['background'].lstrip('#'), 16)
    lines += [f'#define STRIP_Y {s["y"]}', f'#define STRIP_H {s["height"]}',
              f'#define STRIP_BG 0x{(s["opacity"] << 24) | bg:08x}u',
              f'#define SHOW_TICKS {int(s["show_seconds"] * 100)}',
              f'#define START_DELAY_TICKS {int(lay.get("safety", {}).get("start_delay_seconds", 20) * 100)}',
              'static const char UPDATE_PATH[] = "?:\\\\Update\\\\' + lay.get("safety", {}).get("update_file", "8369HD.img") + '";',
              f'#define SLIDE_STEPS {int(s.get("slide_ms", 200) // 10)}']
    for side in ('left', 'right'):
        t = lay[f'temp_{side}']
        lines += [f'#define TEMP_{side.upper()}_X {t["x"]}', f'#define TEMP_{side.upper()}_Y {t["y"]}',
                  f'#define TEMP_{side.upper()}_RIGHT_ALIGN {int(t.get("align") == "right")}']
    fp = lay['fan_panel']
    lines += [f'#define FAN_PANEL_X {fp["x"]}', f'#define FAN_PANEL_Y {fp["y"]}',
              'static const int16_t FAN_BAR_POS[][2] = { ' +
              ', '.join(f'{{ {x}, {y} }}' for x, y in lay['fan_bars']) + ' };',
              f'#define FAN_BARS {len(lay["fan_bars"])}']
    af = lay['airflow']
    lines += [f'#define AIRFLOW_X {af["x"]}', f'#define AIRFLOW_Y {af["y"]}',
              f'#define CENTER_DEFAULT_AIRFLOW {int(lay.get("center_default", "fan") == "airflow")}']
    for name, p in lay['icons'].items():
        lines += [f'#define ICON_{c_name(name)}_X {p["x"]}', f'#define ICON_{c_name(name)}_Y {p["y"]}']

    # fonts for the radio texts: printable ASCII as alpha-only glyphs (1 byte / pixel), one height per font
    rn, pn = lay.get('radio_name', {}), lay.get('preset_names', {})
    lines += [f'#define RADIO_NAME {int(bool(rn.get("enabled")))}', f'#define PRESET_NAMES {int(bool(pn.get("enabled")))}',
              '/* glyphs: printable ASCII, then n_extra more characters (code points in cp) */',
              'typedef struct { uint16_t h, n_extra; const uint16_t *w; const uint32_t *off; const uint8_t *a; '
              'const uint16_t *cp; } font_t;']
    if rn.get('enabled'):
        lines += font_atlas('FONT_NAME', rn['font'], rn['font_px'])
        lines += [f'#define RADIO_NAME_X {rn["x"]}', f'#define RADIO_NAME_Y {rn["y"]}', f'#define RADIO_NAME_W {rn["w"]}',
                  f'#define RADIO_NAME_COLOR 0x{int(rn["color"].lstrip("#"), 16):06x}u']

    be, do = lay.get('belt', {}), lay.get('doors', {})
    lines += [f'#define BELT {int(bool(be.get("enabled")))}', f'#define DOORS {int(bool(do.get("enabled")))}']
    if be.get('enabled'):
        lines += [f'#define BELT_HIDE_IN_PROJECTION {int(bool(be.get("hide_in_projection", True)))}']
    if do.get('enabled'):
        offs = json.load(open(os.path.join(assets, 'door_offsets.json')))
        for name, (ox, oy) in offs.items():
            lines += [f'#define {c_name(name)}_X {ox}', f'#define {c_name(name)}_Y {oy}']
        lines += [f'#define DOORS_X {do["x"]}', f'#define DOORS_Y {do["y"]}',
                  f'#define DOORS_SCALE {round(do.get("scale", 1.0) * 100)}       /* percent, drawn scaled (no larger art in memory) */',
                  f'#define DOORS_HIDE_TICKS {int(do.get("hide_after_ms", 1500) // 10)}']

    bt, np = lay.get('bt_title', {}), lay.get('now_playing', {})
    lines += [f'#define BT_TITLE {int(bool(bt.get("enabled")))}']
    if bt.get('enabled') or np.get('enabled'):      # the now-playing card uses the same font (bt_title font / font_px)
        lines += font_atlas('FONT_BT_TITLE', bt['font'], bt['font_px'], EXTRA_CHARS)
    if bt.get('enabled'):
        lines += [f'#define BT_TITLE_CX {bt["cx"]}', f'#define BT_TITLE_Y {bt["y"]}', f'#define BT_TITLE_W {bt["max_w"]}',
                  f'#define BT_TITLE_COLOR 0x{int(bt["color"].lstrip("#"), 16):06x}u',
                  'static const char BT_TITLE_EMPTY[] = "' + bt.get('empty', '').replace('"', '') + '";']

    lines += [f'#define NOW_PLAYING {int(bool(np.get("enabled")))}']
    if np.get('enabled'):
        col = lambda k: f'0x{int(np[k].lstrip("#"), 16):06x}u'
        lines += [f'#define NP_X {np["x"]}', f'#define NP_Y {np["y"]}', f'#define NP_W {np["w"]}', f'#define NP_H {np["h"]}',
                  f'#define NP_TICKS {int(np.get("show_ms", 4000) // 10)}', f'#define NP_COVER {np["cover"]}',
                  f'#define NP_BG {col("bg")}', f'#define NP_ALPHA {np["opacity"]}',
                  f'#define NP_TITLE_COLOR {col("title_color")}', f'#define NP_ARTIST_COLOR {col("artist_color")}',
                  f'#define NP_HIDE_IN_PROJECTION {int(bool(np.get("hide_in_projection", True)))}']

    hw = lay.get('home_widgets', {})
    lines += [f'#define HOME_WIDGETS {int(bool(hw.get("enabled")))}']
    if hw.get('enabled'):
        hexcol = lambda k: f'0x{int(hw[k].lstrip("#"), 16):06x}u'
        lines += font_atlas('FONT_WIDGET', hw['font'], hw['font_px'], '°')
        lines += [f'#define HW_Y {hw["y"]}', f'#define HW_W {hw["chip_w"]}', f'#define HW_H {hw["chip_h"]}',
                  f'#define HW_GAP {hw["gap"]}', f'#define HW_RADIUS {hw["radius"]}', f'#define HW_COLOR {hexcol("color")}',
                  f'#define HW_GLASS {hexcol("glass")}', f'#define HW_GLASS_ALPHA {hw["glass_alpha"]}',
                  f'#define HW_LINE_ALPHA {hw["line_alpha"]}']

    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
